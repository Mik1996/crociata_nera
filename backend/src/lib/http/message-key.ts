  CANNOT_REMOVE_OWN_ADMIN = 'ERROR.CANNOT_REMOVE_OWN_ADMIN',

  // Validation
  INVALID_JSON = 'ERROR.INVALID_JSON',
  INVALID_FIELD = 'ERROR.INVALID_FIELD',
  EMAIL_SHOULD_NOT_BE_EMPTY = 'ERROR.EMAIL_SHOULD_NOT_BE_EMPTY',
  EMAIL_MUST_BE_AN_EMAIL = 'ERROR.EMAIL_MUST_BE_AN_EMAIL',
  USERNAME_SHOULD_NOT_BE_EMPTY = 'ERROR.USERNAME_SHOULD_NOT_BE_EMPTY',
