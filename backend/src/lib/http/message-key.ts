/**
 * Message keys returned in `BaseResult.messages`. The frontend translates them
 * (ngx-translate), so the API never returns human-readable text.
 */
export enum MessageKey {
  // Success
  USER_CREATED = 'SUCCESS.USER_CREATED',
  SIGNED_IN = 'SUCCESS.SIGNED_IN',
  SIGNED_OUT = 'SUCCESS.SIGNED_OUT',
  TOKEN_REFRESHED = 'SUCCESS.TOKEN_REFRESHED',
  WAR_CREATED = 'SUCCESS.WAR_CREATED',
  WAR_UPDATED = 'SUCCESS.WAR_UPDATED',
  WAR_UNCHANGED = 'SUCCESS.WAR_UNCHANGED',

  // Authentication
  UNAUTHORIZED = 'ERROR.UNAUTHORIZED',
  FORBIDDEN = 'ERROR.FORBIDDEN',
  INVALID_TOKEN = 'ERROR.INVALID_TOKEN',
  INVALID_CREDENTIALS = 'ERROR.INVALID_CREDENTIALS',
  INVALID_REFRESH_TOKEN = 'ERROR.INVALID_REFRESH_TOKEN',
  ORIGIN_NOT_ALLOWED = 'ERROR.ORIGIN_NOT_ALLOWED',
  USER_NOT_FOUND = 'ERROR.USER_NOT_FOUND',
  EMAIL_IS_ALREADY_TAKEN = 'ERROR.EMAIL_IS_ALREADY_TAKEN',
  USERNAME_IS_ALREADY_TAKEN = 'ERROR.USERNAME_IS_ALREADY_TAKEN',

  // Validation
  INVALID_JSON = 'ERROR.INVALID_JSON',
  INVALID_FIELD = 'ERROR.INVALID_FIELD',
  EMAIL_SHOULD_NOT_BE_EMPTY = 'ERROR.EMAIL_SHOULD_NOT_BE_EMPTY',
  EMAIL_MUST_BE_AN_EMAIL = 'ERROR.EMAIL_MUST_BE_AN_EMAIL',
  USERNAME_SHOULD_NOT_BE_EMPTY = 'ERROR.USERNAME_SHOULD_NOT_BE_EMPTY',
  USERNAME_IS_NOT_VALID = 'ERROR.USERNAME_IS_NOT_VALID',
  IDENTIFIER_SHOULD_NOT_BE_EMPTY = 'ERROR.IDENTIFIER_SHOULD_NOT_BE_EMPTY',
  PASSWORD_SHOULD_NOT_BE_EMPTY = 'ERROR.PASSWORD_SHOULD_NOT_BE_EMPTY',
  PASSWORD_IS_NOT_STRONG_ENOUGH = 'ERROR.PASSWORD_IS_NOT_STRONG_ENOUGH',
  PASSWORD_IS_TOO_LONG = 'ERROR.PASSWORD_IS_TOO_LONG',
  REPEAT_PASSWORD_SHOULD_NOT_BE_EMPTY = 'ERROR.REPEAT_PASSWORD_SHOULD_NOT_BE_EMPTY',
  PASSWORDS_DO_NOT_MATCH = 'ERROR.PASSWORDS_DO_NOT_MATCH',
  PLAYER_TAG_IS_NOT_VALID = 'ERROR.PLAYER_TAG_IS_NOT_VALID',

  // Wars
  WAR_NOT_FOUND = 'ERROR.WAR_NOT_FOUND',
  WAR_IS_NOT_SAVABLE = 'ERROR.WAR_IS_NOT_SAVABLE',
  WAR_CLAN_NOT_ALLOWED = 'ERROR.WAR_CLAN_NOT_ALLOWED',

  // Generic
  NOT_FOUND = 'ERROR.NOT_FOUND',
  TOO_MANY_REQUESTS = 'ERROR.TOO_MANY_REQUESTS',
  SERVICE_UNAVAILABLE = 'ERROR.SERVICE_UNAVAILABLE',
  UNHANDLED_ERROR = 'ERROR.UNHANDLED_ERROR',
}

const MESSAGE_KEYS = new Set<string>(Object.values(MessageKey));

export function isMessageKey(value: unknown): value is MessageKey {
  return typeof value === 'string' && MESSAGE_KEYS.has(value);
}
