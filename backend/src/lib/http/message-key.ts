  EMAIL_VERIFIED = 'SUCCESS.EMAIL_VERIFIED',
  VERIFICATION_EMAIL_SENT = 'SUCCESS.VERIFICATION_EMAIL_SENT',
  USER_UPDATED = 'SUCCESS.USER_UPDATED',

  // Authentication
  UNAUTHORIZED = 'ERROR.UNAUTHORIZED',
  FORBIDDEN = 'ERROR.FORBIDDEN',
  INVALID_TOKEN = 'ERROR.INVALID_TOKEN',
  INVALID_CREDENTIALS = 'ERROR.INVALID_CREDENTIALS',
  INVALID_REFRESH_TOKEN = 'ERROR.INVALID_REFRESH_TOKEN',
  ORIGIN_NOT_ALLOWED = 'ERROR.ORIGIN_NOT_ALLOWED',
