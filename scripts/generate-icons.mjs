const require = createRequire(import.meta.url);
const root = join(dirname(require.resolve('@material-design-icons/svg/package.json')), 'filled');
const iconsDir = new URL('../public/assets/icons/', import.meta.url);
const namesFile = new URL('../src/app/shared/icon/icon-names.ts', import.meta.url);

const names = [...new Set(NAMES)].sort();

mkdirSync(iconsDir, { recursive: true });
for (const file of readdirSync(iconsDir)) {
  if (file.endsWith('.svg')) rmSync(new URL(file, iconsDir));
}

for (const name of names) {
  const svg = readFileSync(join(root, `${name}.svg`), 'utf8').trim();
  const match = /^<svg[^>]*viewBox="0 0 24 24"[^>]*>([\s\S]*)<\/svg>$/.exec(svg);
  if (!match) throw new Error(`Unexpected SVG for "${name}"`);
  const body = match[1].trim();
  if (/<(script|style|image|use|foreignObject)\b|\son\w+=|href=|\sfill=/i.test(body)) {
    throw new Error(`Unexpected content in "${name}"`);
  }
  writeFileSync(
    new URL(`${name}.svg`, iconsDir),
    `<svg xmlns="http://www.w3.org/2000/svg" id="icon" viewBox="0 0 24 24" fill="currentColor">${body}</svg>\n`,
  );
}

writeFileSync(
  namesFile,
  `// Generated by scripts/generate-icons.mjs (\`npm run icons\`): do not edit by hand.
// The drawings are in public/assets/icons/<name>.svg.
// Source: @material-design-icons/svg, filled style (Apache License 2.0).
export const ICON_NAMES = [
${names.map((name) => `  '${name}',`).join('\n')}
] as const;

/** Name of an icon shipped with the site (public/assets/icons/<name>.svg). */
export type IconName = (typeof ICON_NAMES)[number];
`,
);
console.log(`${names.length} icons written to ${iconsDir.pathname}`);
